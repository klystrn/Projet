/* ==========================================================================
   Projet — dashboard.html

   Runs alongside assets/landing.js, which owns the shared chrome (mobile
   menu, audience toggle, nav compaction). This file owns everything inside
   the dashboard itself: which view is showing, every render*() function
   that fills a section from real data, and the company view's candidate
   filter.

   FRONT END ONLY until data-endpoint is set. Every value on the page is
   sample data until then, and every render*() function below falls back to
   leaving that sample content alone if the matching field is absent or
   empty — the standing site-wide rule that a fetch failing (or a field
   simply not being sent) never means a visitor sees a broken or empty page.

   BACKEND HOOKS (Andrei) — five seams, nothing else to rewire:

   1. WHICH VIEW.  Right now the view comes from ?view=student|company, else
      the saved audience mode. There is no view switch on this page at all
      any more: reaching the dashboard means you are signed in, so the
      audience is a fact about the account rather than a preference, and the
      nav's For students / For companies toggle is deliberately absent here.
      Once auth exists, call setView(roleFromSession) directly instead of
      reading ?view=. setView() is also what re-tints the page, by setting
      html[data-audience] — nothing else needs to know about the role.

   2. PROFILE + LISTS.  Wired in full now. Set data-endpoint on
      <body class="dash-page"> and this file fetches it and renders
      everything below from the response:

        {
          "role": "student" | "company",
          "profile": { "initials": "CL", "name": "Chloe Lim",
                       "handle": "@chloelim", "bio": "...",
                       "org": "SUTD · Year 3", "loc": "Singapore",
                       "joined": "Joined February 2026",
                       "tagsLabel": "Skills", "tags": ["Figma", "A11y"],
                       "stats": [{ "label": "Avg. score", "value": "83" }] },
          "metrics":  [{ "value": "85", "label": "Latest score" }],       // student's 3-item row only
          "entries":  [{ "title":"...", "company":"...", "discipline":"...",
                         "date":"Aug 2026", "rank":4, "entrants":38,
                         "score":85, "fit":83, "status":"Interview",
                         "statusKind":"win", "solution":"...",
                         "breakdown":[{"label":"Problem framing","score":88}],
                         "feedback":"..." }],                             // student: past hackathons
          "candidates": [{ "name":"...", "meta":"NUS · Year 3 CS",
                            "skills":["React","TypeScript"], "score":94,
                            "fit":92, "rank":1 }],                        // company: ranked submissions
          "activity":  [{ "kind":"win"|"score"|null, "title":"...",
                           "sub":"...", "date":"28 Aug 2026" }],          // whichever feed matches `role`
          "heatTotal": 52,                                                // student heatmap total — see HEATMAP below
          "company": { ... }                                              // see COMPANY OVERVIEW below
        }

      An empty `entries` array is what drives the student empty state —
      showEmpty(true) below handles the swap, and it still fires even
      before `entries` has real rows to render.

   3. ENTRY DETAIL.  Each past-hackathon row — generated by renderEntries()
      from `entries` above — carries its whole modal payload as data-hk-*
      attributes (title, company, discipline, date, rank, entrants, score,
      fit, status, status-kind, solution, breakdown, feedback), read fresh
      on every open by the modal's own delegated click handler. The modal
      itself needed no changes to pick up real data: it never cached the
      rows, only queries whichever one was clicked. `breakdown` in the API
      response is an array of `{label, score}`; renderEntries() flattens it
      into the comma-separated "Label:score" string the modal already reads
      (pass either shape — an array or that same pre-joined string both
      work, see renderEntries()).

   4. HEATMAP.  Wired for both roles now, but from two different sources —
      read this before assuming either one works like the other.
      buildHeat() still fills the actual 53x7 grid from a seeded PRNG (that
      part is cosmetic filler, not real per-day data — there is no source
      in this file's shape above for individual day-level counts, only a
      total), but the heading total each grid sums to is real once data
      arrives: `companyHeatTotal` is DERIVED from `company.briefs[].submitted`
      (see 5 below, no separate field needed), while `studentHeatTotal` has
      no equivalent to derive from (entries are individual completed
      hackathons, not the same count as "everything entered, scored and
      ranked" the student heatmap claims to cover) — it reads the top-level
      `heatTotal` field directly instead. If per-day granularity ever
      matters, buildHeat()'s cell-generation loop is what to replace; the
      heading-total wiring above it can stay as-is either way.

   5. COMPANY OVERVIEW.  Wired: renderCompanyOverview(data.company), called
      from the fetch handler below when the response carries a `company`
      key. Shape (see HANDOVER.md 2.8 for the full spec):

        {
          "metrics": [{ "value":"3", "label":"Open briefs", "delta":"+1", "direction":"up" }],  // 6
          "funnel":  [{ "label":"Submissions", "count":96, "pctOfTop":100 }],
          "monthly": [{ "month":"Sep", "count":17, "pctOfPeak":100 }],                            // 12, oldest first
          "briefs":  [{ "title":"...", "discipline":"Product", "status":"open",
                        "statusLabel":"Open", "submitted":38, "aboveBar":12,
                        "topScore":94, "closesIn":"6 days" }]
        }

      Deliberately NOT part of the shape: a discipline split or any of the
      four prose notes (the funnel's "X hires from Y submissions...", the
      monthly chart's "busiest month...", the table's "N clear your bar
      most often..."). All of it is derived in JS from `funnel`/`briefs`
      instead of trusted as separate API fields — the sample data's own
      history (see CLAUDE.md "Every company figure derives from the brief
      table") is a dashboard whose charts contradicted each other because
      they were filled in by hand from different sources. Deriving instead
      of accepting parallel fields makes that class of bug structurally
      impossible: there is only one number to get right per fact, not two
      that have to be kept in sync by whoever writes the API.
      buildHeat()'s targetTotal now reads companyHeatTotal, which
      renderCompanyOverview sets from the sum of `briefs[].submitted` and
      re-triggers buildHeat(true) with, so the heatmap's own heading stays
      in agreement with the real total instead of the hardcoded 96 sample.

   6. ACTIONS + PROFILE EDITS.  The Schedule / Compare / Book interviews /
      View submission buttons are inert placeholders — real <button
      type="button"> elements with no handler, NOT href="#" anchors (those
      scrolled the page to the top on every click, which read as a bug
      rather than as "not built yet"). No spec for those yet. Edit profile is wired: set #editForm's data-endpoint
      and it PATCHes { name, org, loc, bio, tags } there instead of only
      writing localStorage["projet:profile"] — see HANDOVER.md 2.10 for
      the full behaviour (success/failure/no-endpoint all handled, the
      dialog's own note text switches to match). reapplyProfileEdits still
      re-applies the localStorage copy on every role switch regardless of
      whether an endpoint is set, so an edit still feels instant on this
      device without waiting on a re-fetch.
   ========================================================================== */
