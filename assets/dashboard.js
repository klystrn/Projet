  var DISCIPLINE_SEGS = ["product", "engineering", "data", "design"];

  /* Coerce an API figure to a number before doing arithmetic on it. JSON
     APIs hand numbers back as strings more often than you'd like (Mongo
     aggregations, ORMs, anything that has been through a spreadsheet), and
     `total += br.submitted` on a string silently CONCATENATES: two briefs
     of "40" and "30" summed to the string "04030", which then drove the
     brief-table note, the discipline percentages and the heatmap total.
     A wrong total is worse than a missing one, because it looks fine. */
  function num(v) {
    var n = typeof v === "number" ? v : parseFloat(v);
    return isFinite(n) ? n : 0;
  }

  // zero-padded rank string, e.g. 4 -> "04" — shared by entries and candidates
  function pad2(n) {
    var s = String(n);
    return s.length < 2 ? "0" + s : s;
  }

  /* Rank-badge tier is a purely visual highlight, not a numeric readout (the
     real rank is already the row's own text). A simple first/last split —
     the newest entry (or top candidate) gets the accent tier, the oldest/
     lowest gets the muted one, everything between stays the plain default
     fill — reads correctly at any list length without a proportional ratio
     to justify or keep in sync with list size. */
  function rankBadgeClass(index, length) {
    if (length <= 1 || index === 0) return "is-top";
    if (index === length - 1) return "is-rest";
    return "";
  }

  function renderStudentMetrics(list) {
    var row = document.querySelector(".dp-metrics:not(.dp-metrics--six)");
    if (!row || !list || !list.length) return;
    row.innerHTML = "";
    list.forEach(function (m) {
      var div = document.createElement("div");
      div.className = "dp-metric";
      div.innerHTML = "<b></b><span></span>";
      div.querySelector("b").textContent = m.value;
      div.querySelector("span").textContent = m.label;
      row.appendChild(div);
    });
  }

  /* Past-hackathon rows. Each generated <button> carries the full data-hk-*
     payload the existing entry-detail modal already reads (see the ENTRY
     DETAIL header comment) — the modal itself needs no changes, since its
     click handler is delegated on #dpEntries and queries data-hk-* fresh on
     every open, not cached at setup time. */
  function renderEntries(entries) {
    var list = document.getElementById("dpEntries");
    if (!list || !entries || !entries.length) return;
    var section = list.closest(".dp-section");
    list.innerHTML = "";
    entries.forEach(function (en, i) {
      var btn = document.createElement("button");
      btn.type = "button";
      btn.className = "dp-card";
      btn.setAttribute("data-hk", "");
      var breakdown = Array.isArray(en.breakdown)
        ? en.breakdown.map(function (b) { return b.label + ":" + b.score; }).join(",")
        : (en.breakdown || "");
      var attrs = {
        title: en.title, company: en.company, discipline: en.discipline,
        date: en.date, rank: en.rank, entrants: en.entrants, score: en.score,
        fit: en.fit, status: en.status, "status-kind": en.statusKind,
        solution: en.solution, feedback: en.feedback, breakdown: breakdown
      };
      Object.keys(attrs).forEach(function (k) {
        var v = attrs[k];
        btn.setAttribute("data-hk-" + k, v == null ? "" : v);
      });
      var rankCls = rankBadgeClass(i, entries.length);
      btn.innerHTML =
        "<span class=\"dp-rank" + (rankCls ? " " + rankCls : "") + "\"></span>" +
        "<span class=\"dp-card-body\"><span class=\"dp-card-title\"></span>" +
        "<span class=\"dp-card-meta\"></span></span>" +
        "<span class=\"dp-pill\"></span>" +
        "<span class=\"dp-score\"><b></b><span></span></span>";
      btn.querySelector(".dp-rank").textContent = pad2(en.rank != null ? en.rank : i + 1);
      btn.querySelector(".dp-card-title").textContent = en.title;
      btn.querySelector(".dp-card-meta").textContent = en.company + " · " + en.discipline + " · " + en.date;
      var pill = btn.querySelector(".dp-pill");
      pill.textContent = en.status;
      pill.classList.toggle("is-quiet", en.statusKind === "quiet");
      btn.querySelector(".dp-score b").textContent = en.score;
      btn.querySelector(".dp-score span").textContent = en.fit + "% fit";
      list.appendChild(btn);
    });
    if (section) {
      var count = section.querySelector(".dp-count");
      if (count) count.textContent = entries.length + (entries.length === 1 ? " entry" : " entries");
      var note = section.querySelector(".dp-listfoot-note");
      if (note) note.textContent = "Showing all " + entries.length + (entries.length === 1 ? " entry" : " entries");
    }
  }

  /* Company candidate cards. The four skill-filter chips (React/A11y/Node)
     stay fixed rather than generated from whichever skills happen to be in
     the current list — same reasoning as the discipline taxonomy in
     renderDisciplineSplit below: a hiring lead filters by the skills they
     usually care about, not by whatever a given fetch happens to contain. */
  function renderCandidates(candidates) {
    var list = document.getElementById("dpCandidates");
    if (!list || !candidates || !candidates.length) return;
    list.innerHTML = "";
    candidates.forEach(function (c, i) {
      var art = document.createElement("article");
      art.className = "dp-card";
      var skills = Array.isArray(c.skills) ? c.skills : [];
      art.setAttribute("data-skills", skills.join(" ").toLowerCase());
      art.setAttribute("data-name", (c.name || "").toLowerCase());
      var rankCls = rankBadgeClass(i, candidates.length);
      var btnCls = rankCls === "is-top" ? "btn-primary" : "btn-ghost";
      art.innerHTML =
        "<span class=\"dp-rank" + (rankCls ? " " + rankCls : "") + "\"></span>" +
        "<div class=\"dp-card-body\"><div class=\"dp-card-title\"></div><div class=\"dp-card-meta\"></div></div>" +
        "<div class=\"dp-chips\"></div>" +
        "<div class=\"dp-score\"><b></b><span>Score</span></div>" +
        "<div class=\"dp-fit\"></div>" +
        "<button type=\"button\" class=\"btn " + btnCls + " btn-sm\">Schedule</button>";
      art.querySelector(".dp-rank").textContent = pad2(c.rank != null ? c.rank : i + 1);
      art.querySelector(".dp-card-title").textContent = c.name;
      art.querySelector(".dp-card-meta").textContent = c.meta || "";
      var chips = art.querySelector(".dp-chips");
      skills.forEach(function (s) {
        var span = document.createElement("span");
        span.className = "dp-chip";
        span.textContent = s;
        chips.appendChild(span);
      });
      art.querySelector(".dp-score b").textContent = c.score;
      art.querySelector(".dp-fit").textContent = (c.fit != null ? c.fit : "") + "%";
      list.appendChild(art);
    });
    applyCandidateFilter();
  }

  /* Per-role activity feed. Only one of #dpFeedStudent/#dpFeedCompany is
     ever rendered per fetch — a single account only ever has one role, so
     there is never a second feed's worth of real data to fill the other
     with. setView() above already recomputes dpActCount from the feed's own
     child count, so nothing here needs to touch that a second time. */
  function renderActivityFeed(feedEl, events) {
    if (!feedEl || !events || !events.length) return;
    feedEl.innerHTML = "";
    events.forEach(function (ev) {
      var li = document.createElement("li");
      li.className = "dp-feed-item";
      li.innerHTML = "<span class=\"dp-feed-dot\" aria-hidden=\"true\"></span>" +
        "<div><b></b><span></span></div><time></time>";
      if (ev.kind) li.querySelector(".dp-feed-dot").setAttribute("data-kind", ev.kind);
      li.querySelector("b").textContent = ev.title;
      li.querySelector("div span").textContent = ev.sub || "";
      li.querySelector("time").textContent = ev.date || "";
      feedEl.appendChild(li);
    });
  }

  function renderCompanyMetrics(list) {
    var row = document.querySelector(".dp-metrics.dp-metrics--six");
    if (!row || !list || !list.length) return;
    row.innerHTML = "";
    list.forEach(function (m) {
      var dir = m.direction === "down" ? "is-down" : m.direction === "flat" ? "is-flat" : "is-up";
      var div = document.createElement("div");
      div.className = "dp-metric";
      div.innerHTML = "<b></b><span></span><i class=\"dp-delta " + dir + "\"></i>";
      div.querySelector("b").textContent = m.value;
      div.querySelector("span").textContent = m.label;
      div.querySelector("i").textContent = m.delta;
      row.appendChild(div);
    });
  }

